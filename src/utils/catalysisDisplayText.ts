export function localizeCatalysisText(value, zh = true) {
  if (!zh || value === null || value === undefined) return value
  const text = String(value)
  if (EXACT_ZH[text]) return EXACT_ZH[text]

  const belowL4 = text.match(/^(\d+) numeric claims remain below L4\.$/)
  if (belowL4) return `${belowL4[1]} 条数值声明尚未精确定位到图表、章节或补充材料。`

  const missingComparison = text.match(/^Required comparison field ([A-Za-z]+) is missing\.$/)
  if (missingComparison) return `缺少同条件比较所需的${COMPARISON_FIELDS_ZH[missingComparison[1]] || missingComparison[1]}。`

  const chineseTaskField = text.match(/^补齐比较条件：([A-Za-z]+)$/)
  if (chineseTaskField) return `补齐比较条件：${COMPARISON_FIELDS_ZH[chineseTaskField[1]] || chineseTaskField[1]}`

  if (text.startsWith("publisher full text · ")) {
    return text
      .replace(/^publisher full text/, "出版方全文")
      .replace("Electrocatalytic CO2 reduction", "电催化 CO₂ 还原")
      .replace("Electrochemical CO2 reduction", "电化学 CO₂ 还原")
      .replace("Electrochemical performance", "电化学性能")
      .replace("Electronic structure and conductivity", "电子结构与电导率")
      .replace("Results and discussion", "结果与讨论")
      .replace(/Fig\.\s*/g, "图 ")
      .replace(/Table\s*/g, "表 ")
  }

  if (text === "Metadata access does not establish permission to reuse full-text-derived claims for model training.") {
    return "获得论文元数据不等于取得全文数据的模型训练使用许可。"
  }
  if (text === "No exact CSD Refcode, CCDC identifier, or provenance-matched canonical ID is available.") {
    return "尚未取得准确的 CSD Refcode、CCDC 编号或来源一致的标准结构标识。"
  }
  if (text === "Precursor, derived, operando, and post-reaction states are not yet experimentally resolved into one active-phase decision.") {
    return "前驱体、衍生态、操作态与反应后状态尚不足以形成明确的活性相结论。"
  }

  return text
}

export function localizeCatalysisBlocker(value, zh = true) {
  if (!zh) return value
  const text = String(value || "")
  if (BLOCKERS_ZH[text]) return BLOCKERS_ZH[text]
  const missing = text.match(/^missing-condition:(.+)$/)
  if (missing) return `缺少${COMPARISON_FIELDS_ZH[missing[1]] || missing[1]}`
  return localizeCatalysisText(text, true)
}
